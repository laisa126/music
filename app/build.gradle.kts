// Optional release signing. If `keystore.properties` (or the matching environment
// variables) are absent we fall back to the debug key so that CI can always
// produce an installable APK without any secrets configured.
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.inputStream().use { load(it) }
    }
}

fun secret(key: String, env: String): String? =
    keystoreProperties.getProperty(key) ?: System.getenv(env)

val releaseStoreFile = secret("storeFile", "AURORA_KEYSTORE_FILE")
val releaseStorePassword = secret("storePassword", "AURORA_KEYSTORE_PASSWORD")
val releaseKeyAlias = secret("keyAlias", "AURORA_KEY_ALIAS")
val releaseKeyPassword = secret("keyPassword", "AURORA_KEY_PASSWORD")
val hasReleaseSigning = !releaseStoreFile.isNullOrBlank() &&
    rootProject.file(releaseStoreFile).exists() &&
    !releaseStorePassword.isNullOrBlank() &&
    !releaseKeyAlias.isNullOrBlank() &&
    !releaseKeyPassword.isNullOrBlank()

